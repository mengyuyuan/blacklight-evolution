accent=(190,74,81,255)
def strokes(index,lines):
    tile=Image.new('RGBA',(32,32))
    d=ImageDraw.Draw(tile)
    for i,points in enumerate(lines):
        d.line(points,fill=accent if i==len(lines)-1 else ink,width=2,joint='curve')
    canvas.paste(tile,(32*(index%4),32*(index//4)))
