"""Build original editable vehicle assets and server mounts from one JSON source.

No network, Gradle, game process or original-game pixels are used. --check is
read-only and compares every generated byte; --preview additionally uses Pillow
to render the actual authored cuboids, not a separate concept model.
"""
from __future__ import annotations

import argparse
import base64
import copy
import hashlib
import io
import json
import math
from pathlib import Path
import struct
import uuid
import zlib

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / "art/military-vehicles"
SOURCE = ART / "vehicle-authoring.json"
CLIENT = ROOT / "src/main/resources/assets/blacklight/military/vehicle-models.json"
MOUNTS = ROOT / "src/main/resources/data/blacklight/military/vehicle-mounts.json"
VEHICLES = ROOT / "src/main/resources/data/blacklight/military/vehicles.json"
TEXTURES = ROOT / "src/main/resources/assets/blacklight/textures/entity"
NAMESPACE = uuid.UUID("a1602906-e9c6-46e7-93dc-054fcd6f3bc6")
ATLAS = 2048


def encoded_json(value):
    return (json.dumps(value, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def uid(name):
    return str(uuid.uuid5(NAMESPACE, name))


def resize_authoring(source, sizes):
    """Bake physical proportions into source geometry; never scale a renderer."""
    source = copy.deepcopy(source)
    for name, dimensions in sizes.items():
        chassis = source["chassis"][name]
        old = chassis["dimensions"]
        sx, sy, sz = dimensions[0]/old[0], dimensions[2]/old[2], dimensions[1]/old[1]
        scale = [sx, sy, sz]
        pivots = {bone["name"]: bone["pivot"][:] for bone in chassis["bones"]}
        for bone in chassis["bones"]:
            bone["pivot"] = [round(v*s, 8) for v, s in zip(bone["pivot"], scale)]
        for part in chassis["parts"]:
            box = part["box"]
            resized = [round(v*scale[i % 3], 8) for i, v in enumerate(box)]
            if "wheel_" in part["bone"]:
                # Axle spacing follows the hull; tires and hubs keep a circular profile.
                pivot = pivots[part["bone"]]
                radial = min(sy, sz)
                for i in (1, 2):
                    resized[i] = round(pivot[i]*scale[i] + (box[i]-pivot[i])*radial, 8)
                    resized[i+3] = round(box[i+3]*radial, 8)
            part["box"] = resized
        for anchor_name, anchor in chassis["anchors"].items():
            anchor["position"] = [round(v*s, 8) for v, s in zip(anchor["position"], scale)]
            if anchor_name.startswith("exit_"):
                anchor["position"][1] = .1
        chassis["barrelRadius"] = round(chassis["barrelRadius"]*max(sx, sy), 8)
        chassis["dimensions"] = dimensions
    return source


def pixels_png(rgb, width, height):
    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xffffffff)
    rows = b"".join(b"\0" + rgb[y * width * 3:(y + 1) * width * 3] for y in range(height))
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)) + chunk(b"IDAT", zlib.compress(rows, 9)) + chunk(b"IEND", b"")


def validate(source):
    assert source["schemaVersion"] == 1
    assert set(source["chassis"]) == {"truck", "apc", "tank"}
    for name, chassis in source["chassis"].items():
        bones = chassis["bones"]
        assert [b["name"] for b in bones[:2]] == ["root", "body"]
        known = set()
        for bone in bones:
            assert bone["name"] not in known
            assert bone["parent"] is None or bone["parent"] in known
            assert all(math.isfinite(v) for v in bone["pivot"])
            known.add(bone["name"])
        assert len({p["name"] for p in chassis["parts"]}) == len(chassis["parts"])
        width, length, height = chassis["dimensions"]
        for part in chassis["parts"]:
            assert part["bone"] in known and part["material"] in source["palettes"]["military"]
            assert len(part["box"]) == 6 and all(math.isfinite(n) for n in part["box"])
            assert all(n > 0 for n in part["box"][3:])
            if not part.get("weaponOverhang", False):
                x, y, z, w, h, d = part["box"]
                assert -width / 2 - 1e-7 <= x and x + w <= width / 2 + 1e-7, (name, part["name"], "width")
                assert -length / 2 - 1e-7 <= z and z + d <= length / 2 + 1e-7, (name, part["name"], "length")
                assert y >= -1e-7 and y + h <= height + 1e-7, (name, part["name"], "height")
        for anchor in chassis["anchors"].values():
            assert anchor["frame"] in known
            assert len(anchor["position"]) == 3 and all(math.isfinite(n) for n in anchor["position"])
        seats = [a for a in chassis["anchors"] if a.startswith("seat_")]
        assert len(seats) == {"truck": 8, "apc": 8, "tank": 3}[name]
        for weapon in chassis["weapons"]:
            muzzle = chassis["anchors"]["muzzle_" + weapon["id"]]
            breech = chassis["anchors"]["breech_" + weapon["id"]]
            assert muzzle["frame"] == breech["frame"]
            assert muzzle["position"][2] > breech["position"][2]
            # The far end of the actual authored barrel must be this muzzle.
            end_part = next(p for p in chassis["parts"] if p["name"] == weapon["muzzlePart"])
            x, y, z, w, h, d = end_part["box"]
            assert all(abs(a - b) < 1e-7 for a, b in zip([x+w/2, y+h/2, z+d], muzzle["position"])), weapon


def layout(source):
    cursor_x, cursor_y, row_h = 2, 2, 0
    result = {}
    for name, chassis in source["chassis"].items():
        for part in chassis["parts"]:
            _, _, _, w, h, d = [n * 16 for n in part["box"]]
            tw, th = math.ceil(2*(w+d)) + 2, math.ceil(h+d) + 2
            if cursor_x + tw + 2 > ATLAS:
                cursor_x, cursor_y, row_h = 2, cursor_y + row_h + 2, 0
            assert cursor_y + th + 2 <= ATLAS, "atlas full"
            result[(name, part["name"])] = [cursor_x, cursor_y, tw, th]
            cursor_x += tw + 2
            row_h = max(row_h, th)
    return result


def atlas(source, rectangles, faction):
    pixels = bytearray(b"\x1b\x20\x20" * ATLAS * ATLAS)
    palette = source["palettes"][faction]
    for name, chassis in source["chassis"].items():
        for part in chassis["parts"]:
            u, v, width, height = rectangles[(name, part["name"])]
            base = bytes.fromhex(palette[part["material"]].lstrip("#"))
            paint = part["material"] in {"armor", "armor_light", "armor_dark", "canvas"}
            seed = int(hashlib.sha256(part["name"].encode("ascii")).hexdigest()[:4], 16)
            for y in range(v, v+height):
                for x in range(u, u+width):
                    # Small authored pixel variation; no photo textures or random seed.
                    jitter = ((x*17 + y*31 + (x//5)*7) % 9) - 4
                    pigment = base
                    lx, ly = x-u, y-v
                    if paint:
                        patch = (lx//13 + ly//9 + (lx+ly)//19 + seed) % 7
                        if faction == "military" and patch in (0, 1, 4):
                            pigment = bytes.fromhex(palette["armor_dark" if patch < 2 else "armor_light"][1:])
                        elif faction == "blackwatch":
                            pigment = bytes.fromhex(palette["armor_dark" if patch < 3 else part["material"]][1:])
                            if ("side" in part["name"] or "skirt" in part["name"] or "door" in part["name"]) and (lx+ly//2+seed) % 53 < 2:
                                pigment = bytes.fromhex(palette["marker"][1:])
                    if part["material"] in {"glass", "lamp", "marker", "tail_lamp"}:
                        jitter = 0
                    color = bytes(max(0, min(255, c+jitter)) for c in pigment)
                    pos = (y*ATLAS+x)*3
                    pixels[pos:pos+3] = color
            def pixel(x, y, color):
                if u <= x < u+width and v <= y < v+height:
                    pos = (y*ATLAS+x)*3
                    pixels[pos:pos+3] = bytes.fromhex(color[1:])
            uv_faces = faces_uv(part, (u, v))
            if paint and any(word in part["name"] for word in ("door", "skirt", "canvas_side")):
                for face in uv_faces.values():
                    a, b, c, d = face
                    if c-a >= 12 and d-b >= 8:
                        cx, cy = int((a+c)/2), int((b+d)/2)
                        for dy in range(5):
                            for dx in range(5):
                                mark = dy in (0, 2, 4) and dx < 4 if faction == "military" else (dx == 0 or dy == 0 or dx+dy == 5)
                                if mark:
                                    pixel(cx+dx-2, cy+dy-2, palette["marker"])
            # Small original optical slits are painted at the exact authored camera ports.
            bx, by, bz, bw, bh, bd = part["box"]
            for anchor_id in part.get("viewports", []):
                px, py, pz = chassis["anchors"][anchor_id]["position"]
                candidates = [(abs(px-bx), "west", (pz-bz)/bd, (by+bh-py)/bh),
                    (abs(px-bx-bw), "east", (pz-bz)/bd, (by+bh-py)/bh),
                    (abs(pz-bz), "north", (px-bx)/bw, (by+bh-py)/bh),
                    (abs(pz-bz-bd), "south", (px-bx)/bw, (by+bh-py)/bh),
                    (abs(py-by-bh), "up", (px-bx)/bw, (pz-bz)/bd)]
                _, side, fx, fy = min(candidates)
                a, b, c, d = uv_faces[side]
                cx, cy = int(a+fx*(c-a)), int(b+fy*(d-b))
                for dy in range(-1, 2):
                    for dx in range(-3, 4):
                        tx, ty = cx+dx, cy+dy
                        if a <= tx < c and b <= ty < d:
                            pixel(tx, ty, palette["glass"] if dy == 0 and abs(dx) < 3 else palette["metal"])
    return pixels_png(pixels, ATLAS, ATLAS)


def faces_uv(part, uv):
    w, h, d = [n*16 for n in part["box"][3:]]
    u, v = uv[:2]
    return {
        "north": [u+d, v+d, u+d+w, v+d+h],
        "east": [u, v+d, u+d, v+d+h],
        "south": [u+d+w+d, v+d, u+d+w+d+w, v+d+h],
        "west": [u+d+w, v+d, u+d+w+d, v+d+h],
        "up": [u+d, v, u+d+w, v+d],
        "down": [u+d+w, v, u+d+w+w, v+d],
    }


def blockbench(name, chassis, rectangles, textures):
    elements = []
    groups = {}
    for bone in chassis["bones"]:
        groups[bone["name"]] = {"name": bone["name"], "uuid": uid(name+"/bone/"+bone["name"]),
            "origin": [v*16 for v in bone["pivot"]], "rotation": [0, 0, 0], "export": True, "isOpen": True, "children": []}
    for part in chassis["parts"]:
        x, y, z, w, h, d = part["box"]
        element_id = uid(name+"/part/"+part["name"])
        elements.append({"name": part["name"], "uuid": element_id, "type": "cube", "box_uv": False,
            "from": [x*16, y*16, z*16], "to": [(x+w)*16, (y+h)*16, (z+d)*16],
            "origin": groups[part["bone"]]["origin"], "rotation": [0, 0, 0],
            "faces": {f: {"uv": coords, "texture": 0} for f, coords in faces_uv(part, rectangles[(name, part["name"])]).items()}})
        groups[part["bone"]]["children"].append(element_id)
    for anchor_name, anchor in chassis["anchors"].items():
        groups[anchor["frame"]]["children"].append({"name": anchor_name, "uuid": uid(name+"/anchor/"+anchor_name),
            "origin": [v*16 for v in anchor["position"]], "rotation": [0,0,0], "export": True, "children": []})
    for bone in reversed(chassis["bones"]):
        if bone["parent"]:
            groups[bone["parent"]]["children"].append(groups[bone["name"]])
    return {"meta": {"format_version": "4.10", "model_format": "bedrock", "box_uv": False},
        "name": "Blacklight original "+name, "model_identifier": "blacklight_"+name,
        "visible_box": [12, 5, 0], "resolution": {"width": ATLAS, "height": ATLAS},
        "elements": elements, "outliner": [groups["root"]],
        "textures": [{"name": faction, "id": str(i), "uuid": uid("texture/"+faction), "mode": "bitmap",
            "path": "textures/"+faction+".png", "source": "data:image/png;base64,"+base64.b64encode(png).decode("ascii"),
            "width": ATLAS, "height": ATLAS, "uv_width": ATLAS, "uv_height": ATLAS, "internal": True}
            for i, (faction, png) in enumerate(textures.items())]}


def outputs(source):
    validate(source)
    source_hash = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    rects = layout(source)
    textures = {f: atlas(source, rects, f) for f in source["palettes"]}
    generated = {}
    runtime = {"schemaVersion": 1, "source": "art/military-vehicles/vehicle-authoring.json", "sourceSha256": source_hash,
        "coordinateSystem": source["coordinateSystem"],
        "modelPartContract": {"unitsPerBlock": 16, "axisScale": [16,16,16], "rootOrigin": [0,0,0],
            "pivot": "parent-relative model units", "box": "bone-relative [x,y,z,w,h,d] model units",
            "render": "ModelPart.render emits 1/16 units. Custom renderer must not apply Humanoid's negative Y/Z scale or +24 model offset.",
            "rotation": "bone rest positions are absolute author blocks; runtime bone pivots below are relative to parent. Apply yaw to turret_yaw and pitch to gun_pitch."},
        "textureWidth": ATLAS, "textureHeight": ATLAS,
        "textures": {f: "blacklight:textures/entity/military_vehicles_"+f+".png" for f in textures},
        "palettes": source["palettes"], "chassis": {}}
    mounts = {"schemaVersion": 1, "sourceSha256": source_hash, "coordinateSystem": source["coordinateSystem"], "chassis": {}}
    for name, chassis in source["chassis"].items():
        pivots = {b["name"]: b["pivot"] for b in chassis["bones"]}
        bones = []
        for bone in chassis["bones"]:
            parent_pivot = pivots[bone["parent"]] if bone["parent"] else [0,0,0]
            bones.append({"name": bone["name"], "parent": bone["parent"],
                "pivot": [round((a-b)*16, 6) for a,b in zip(bone["pivot"], parent_pivot)], "pivotBlocks": bone["pivot"]})
        parts = []
        for part in chassis["parts"]:
            pivot = pivots[part["bone"]]
            box = [round((part["box"][i]-pivot[i])*16, 6) for i in range(3)] + [round(v*16, 6) for v in part["box"][3:]]
            parts.append({"name": part["name"], "parent": part["bone"], "box": box,
                "uv": rects[(name,part["name"])][:2], "material": part["material"], "weaponOverhang": part.get("weaponOverhang", False)})
        runtime["chassis"][name] = {"dimensions": chassis["dimensions"], "referenceStatus": chassis["referenceStatus"],
            "bones": bones, "parts": parts, "anchors": chassis["anchors"]}
        mounts["chassis"][name] = {"turretPivot": pivots.get("turret_yaw",[0,0,0]), "gunPivot": pivots.get("gun_pitch",[0,0,0]),
            "barrelRadius": chassis["barrelRadius"], "anchors": chassis["anchors"]}
        generated[ART/(name+".bbmodel")] = encoded_json(blockbench(name,chassis,rects,textures))
    generated[CLIENT], generated[MOUNTS] = encoded_json(runtime), encoded_json(mounts)
    definitions = json.loads(VEHICLES.read_text(encoding="utf8"))
    for vehicle in definitions["vehicles"]:
        vehicle.update(zip(("width", "length", "height"), source["chassis"][vehicle["id"]]["dimensions"]))
    generated[VEHICLES] = encoded_json(definitions)
    for faction,png in textures.items():
        generated[ART/"textures"/(faction+".png")] = png
        generated[TEXTURES/("military_vehicles_"+faction+".png")] = png
    return generated


def preview(source):
    from PIL import Image, ImageDraw
    # Face-sorted orthographic render of source cubes, with labelled axes/anchors.
    im = Image.new("RGB", (1500,1000), "#edf0ec")
    draw = ImageDraw.Draw(im)
    for row, faction in enumerate(source["palettes"]):
        for col,(name,chassis) in enumerate(source["chassis"].items()):
            cx, cy, scale = 250+col*500, 290+row*480, 48
            def project(p):
                x,y,z = p
                return (cx+(x-z*.65)*scale,cy+(-y+(x+z)*.30)*scale)
            faces=[]
            for part in chassis["parts"]:
                x,y,z,w,h,d=part["box"]
                rgb=tuple(bytes.fromhex(source["palettes"][faction][part["material"]][1:]))
                for pts,shade in [([(x+w,y,z),(x+w,y,z+d),(x+w,y+h,z+d),(x+w,y+h,z)],.70),
                                  ([(x,y,z+d),(x+w,y,z+d),(x+w,y+h,z+d),(x,y+h,z+d)],.83),
                                  ([(x,y+h,z),(x+w,y+h,z),(x+w,y+h,z+d),(x,y+h,z+d)],1.12)]:
                    depth=sum(p[0]*.65+p[2]+p[1]*.495 for p in pts)/4
                    faces.append((depth,pts,tuple(min(255,int(c*shade)) for c in rgb)))
            for _,pts,color in sorted(faces,key=lambda a:a[0]):
                draw.polygon([project(p) for p in pts],fill=color,outline=tuple(max(0,int(c*.70)) for c in color))
            draw.text((cx-200,45+row*480),f"{name.upper()} / {faction}   {chassis['dimensions']} blocks",fill="#233332")
            draw.text((cx-200,410+row*480),"Actual source geometry / offline preview / no client acceptance",fill="#667370")
    path=ART/"previews"/"vehicles-isometric.png"
    path.parent.mkdir(parents=True,exist_ok=True)
    im.save(path)
    return path


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check",action="store_true",help="read-only deterministic comparison")
    parser.add_argument("--preview",action="store_true",help="generate a Pillow geometry preview")
    parser.add_argument("--resize", nargs=4, action="append", metavar=("CHASSIS", "WIDTH", "LENGTH", "HEIGHT"),
        help="bake physical dimensions into authoring before generating; wheels remain circular")
    args=parser.parse_args()
    source=json.loads(SOURCE.read_text(encoding="utf-8"))
    if args.resize:
        assert not args.check, "--check cannot resize authoring"
        sizes = {name: [float(w), float(d), float(h)] for name, w, d, h in args.resize}
        assert all(name in source["chassis"] and all(math.isfinite(v) and v > 0 for v in dims)
                   for name, dims in sizes.items())
        source = resize_authoring(source, sizes)
        validate(source)
        SOURCE.write_bytes(encoded_json(source))
    generated=outputs(source)
    stale=[]
    for path,data in generated.items():
        if args.check:
            if not path.exists() or path.read_bytes()!=data:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_bytes(data)
    if stale:
        raise SystemExit("STALE: "+", ".join(stale))
    if args.preview:
        assert not args.check,"--check cannot write previews"
        print(preview(source).relative_to(ROOT))
    print(json.dumps({"mode":"check" if args.check else "build", "files":len(generated),
        "parts":{name:len(c["parts"]) for name,c in source["chassis"].items()},
        "sourceSha256":hashlib.sha256(SOURCE.read_bytes()).hexdigest(), "clientAccepted":False}))


if __name__=="__main__":
    main()
